// Always derive editable Tokyo fields from the session instant, rather than a
// driver's environment-dependent serialization of timestamp without time zone.
export function sessionEditorDateTime(startsAt: string) {
  const parts = Object.fromEntries(
    new Intl.DateTimeFormat("en-CA", {
      timeZone: "Asia/Tokyo",
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      hourCycle: "h23",
    })
      .formatToParts(new Date(startsAt))
      .map((p) => [p.type, p.value]),
  );
  return {
    date: `${parts.year}-${parts.month}-${parts.day}`,
    time: `${parts.hour}:${parts.minute}`,
  };
}

export function dateInputValue(value: string) {
  return value.slice(0, 10);
}
